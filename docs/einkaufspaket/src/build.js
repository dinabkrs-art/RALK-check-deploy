// Renders the procurement pack (Einkaufspaket) HTML sources to A4 PDFs.
// Usage: NODE_PATH=$(npm root -g) node docs/einkaufspaket/src/build.js
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');

const SRC = __dirname;
const OUT = path.resolve(SRC, '..');
const LICENCE = path.resolve(SRC, '../../../ralk-site/licence.html');

// Licence terms: take the EN/FR articles from ralk-site/licence.html (source of truth)
// and wrap them in the print layout; site header, footer and scripts are not carried over.
function buildLicence() {
  const html = fs.readFileSync(LICENCE, 'utf8');
  for (const lang of ['en', 'fr']) {
    const m = html.match(new RegExp(`<article data-lang="${lang}"[^>]*>([\\s\\S]*?)</article>`));
    if (!m) throw new Error('licence article not found: ' + lang);
    const label = lang === 'en' ? ['Contract documents', 'Licence terms'] : ['Documents contractuels', 'Conditions de licence'];
    const page = `<!doctype html>
<html lang="${lang}">
<head><meta charset="utf-8"><title>${label[1]} RALK</title><link rel="stylesheet" href="pack.css"></head>
<body>
<!-- generated by build.js from ralk-site/licence.html; edit the source there -->
<div class="band"><img src="logo.png" alt="RALK"><div class="doc"><span>${label[0]}</span><b>${label[1]}</b></div></div>
<main class="legal">${m[1]}</main>
</body>
</html>
`;
    fs.writeFileSync(path.join(SRC, `licence-terms-${lang}.html`), page, 'utf8');
  }
}

const DOCS = [
  'company-profile-en', 'company-profile-fr',
  'price-sheet-en', 'price-sheet-fr',
  'licence-terms-en', 'licence-terms-fr',
  'security-and-quality-factsheet-en', 'security-and-quality-factsheet-fr',
];

(async () => {
  buildLicence();
  const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
  const page = await browser.newPage();
  for (const name of DOCS) {
    const file = path.join(SRC, name + '.html');
    if (!fs.existsSync(file)) { console.log('skip (missing)', name); continue; }
    await page.goto('file://' + file, { waitUntil: 'networkidle' });
    await page.evaluate(() => document.fonts.ready);
    const fr = name.endsWith('-fr');
    if (!name.startsWith('licence-terms')) {
      // One-pagers: content width = A4 minus side margins; shrink slightly if the page would overflow.
      await page.setViewportSize({ width: 688, height: 1000 });
      const zoom = await page.evaluate(() => {
        const avail = 1010; // printable height in CSS px (297mm - 26mm margins), small safety
        let z = 1;
        while (document.documentElement.scrollHeight > avail && z > 0.8) {
          z = Math.round((z - 0.01) * 100) / 100;
          document.body.style.zoom = String(z);
        }
        return z;
      });
      if (zoom < 1) console.log(`  ${name}: zoom ${zoom.toFixed(3)}`);
    }
    await page.pdf({
      path: path.join(OUT, name + '.pdf'),
      format: 'A4',
      printBackground: true,
      margin: { top: '12mm', bottom: '14mm', left: '14mm', right: '14mm' },
      displayHeaderFooter: true,
      headerTemplate: '<span></span>',
      footerTemplate: `<div style="width:100%;font-family:Inter,Arial,sans-serif;font-size:7px;color:#777;padding:0 14mm;display:flex;justify-content:space-between;">
        <span>RALK · Hafenstraße 25–27 · 68159 Mannheim · ${fr ? 'Allemagne' : 'Germany'} · info@ralk.io · ralk.io</span><span>${fr ? 'Version octobre 2026' : 'Version October 2026'} · Page <span class="pageNumber"></span> / <span class="totalPages"></span></span></div>`,
    });
    console.log('ok', name);
  }
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
